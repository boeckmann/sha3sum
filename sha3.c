static void keccak64(u64 a[])
{
    static u64 rc[] = {
	0x0000000000000001, 0x0000000000008082, 0x800000000000808a, 0x8000000080008000,
	0x000000000000808b, 0x0000000080000001, 0x8000000080008081, 0x8000000000008009,
	0x000000000000008a, 0x0000000000000088, 0x0000000080008009, 0x000000008000000a,
	0x000000008000808b, 0x800000000000008b, 0x8000000000008089, 0x8000000000008003,
	0x8000000000008002, 0x8000000000000080, 0x000000000000800a, 0x800000008000000a,
	0x8000000080008081, 0x8000000000008080, 0x0000000080000001, 0x8000000080008008
    };
    u64 b[25];
    u64 c[5], d[5];
    int round;

    for (round = 0; round < 24; round++) {
	/* theta */
	c[0] = a[0] ^ a[5] ^ a[10] ^ a[15] ^ a[20];
	c[1] = a[1] ^ a[6] ^ a[11] ^ a[16] ^ a[21];
	c[2] = a[2] ^ a[7] ^ a[12] ^ a[17] ^ a[22];
	c[3] = a[3] ^ a[8] ^ a[13] ^ a[18] ^ a[23];
	c[4] = a[4] ^ a[9] ^ a[14] ^ a[19] ^ a[24];
	d[0] = ((c[1] << 1) | (c[1] >> 63)) ^ c[4];
	d[1] = ((c[2] << 1) | (c[2] >> 63)) ^ c[0];
	d[2] = ((c[3] << 1) | (c[3] >> 63)) ^ c[1];
	d[3] = ((c[4] << 1) | (c[4] >> 63)) ^ c[2];
	d[4] = ((c[0] << 1) | (c[0] >> 63)) ^ c[3];
	a[0] ^= d[0];
	a[1] ^= d[1];
	a[2] ^= d[2];
	a[3] ^= d[3];
	a[4] ^= d[4];
	a[5] ^= d[0];
	a[6] ^= d[1];
	a[7] ^= d[2];
	a[8] ^= d[3];
	a[9] ^= d[4];
	a[10] ^= d[0];
	a[11] ^= d[1];
	a[12] ^= d[2];
	a[13] ^= d[3];
	a[14] ^= d[4];
	a[15] ^= d[0];
	a[16] ^= d[1];
	a[17] ^= d[2];
	a[18] ^= d[3];
	a[19] ^= d[4];
	a[20] ^= d[0];
	a[21] ^= d[1];
	a[22] ^= d[2];
	a[23] ^= d[3];
	a[24] ^= d[4];

	/* rho */
	b[0] = a[0];
	b[1] = (a[1] << 1) | (a[1] >> 63);
	b[10] = (a[10] << 3) | (a[10] >> 61);
	b[7] = (a[7] << 6) | (a[7] >> 58);
	b[11] = (a[11] << 10) | (a[11] >> 54);
	b[17] = (a[17] << 15) | (a[17] >> 49);
	b[18] = (a[18] << 21) | (a[18] >> 43);
	b[3] = (a[3] << 28) | (a[3] >> 36);
	b[5] = (a[5] << 36) | (a[5] >> 28);
	b[16] = (a[16] << 45) | (a[16] >> 19);
	b[8] = (a[8] << 55) | (a[8] >> 9);
	b[21] = (a[21] << 2) | (a[21] >> 62);
	b[24] = (a[24] << 14) | (a[24] >> 50);
	b[4] = (a[4] << 27) | (a[4] >> 37);
	b[15] = (a[15] << 41) | (a[15] >> 23);
	b[23] = (a[23] << 56) | (a[23] >> 8);
	b[19] = (a[19] << 8) | (a[19] >> 56);
	b[13] = (a[13] << 25) | (a[13] >> 39);
	b[12] = (a[12] << 43) | (a[12] >> 21);
	b[2] = (a[2] << 62) | (a[2] >> 2);
	b[20] = (a[20] << 18) | (a[20] >> 46);
	b[14] = (a[14] << 39) | (a[14] >> 25);
	b[22] = (a[22] << 61) | (a[22] >> 3);
	b[9] = (a[9] << 20) | (a[9] >> 44);
	b[6] = (a[6] << 44) | (a[6] >> 20);

	/* pi, chi & iota */
	a[0] = b[0] ^ (~b[6] & b[12]) ^ rc[round];
	a[1] = b[6] ^ (~b[12] & b[18]);
	a[2] = b[12] ^ (~b[18] & b[24]);
	a[3] = b[18] ^ (~b[24] & b[0]);
	a[4] = b[24] ^ (~b[0] & b[6]);
	a[5] = b[3] ^ (~b[9] & b[10]);
	a[6] = b[9] ^ (~b[10] & b[16]);
	a[7] = b[10] ^ (~b[16] & b[22]);
	a[8] = b[16] ^ (~b[22] & b[3]);
	a[9] = b[22] ^ (~b[3] & b[9]);
	a[10] = b[1] ^ (~b[7] & b[13]);
	a[11] = b[7] ^ (~b[13] & b[19]);
	a[12] = b[13] ^ (~b[19] & b[20]);
	a[13] = b[19] ^ (~b[20] & b[1]);
	a[14] = b[20] ^ (~b[1] & b[7]);
	a[15] = b[4] ^ (~b[5] & b[11]);
	a[16] = b[5] ^ (~b[11] & b[17]);
	a[17] = b[11] ^ (~b[17] & b[23]);
	a[18] = b[17] ^ (~b[23] & b[4]);
	a[19] = b[23] ^ (~b[4] & b[5]);
	a[20] = b[2] ^ (~b[8] & b[14]);
	a[21] = b[8] ^ (~b[14] & b[15]);
	a[22] = b[14] ^ (~b[15] & b[21]);
	a[23] = b[15] ^ (~b[21] & b[2]);
	a[24] = b[21] ^ (~b[2] & b[8]);
    }
}

